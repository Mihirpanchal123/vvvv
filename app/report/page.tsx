"use client";

import { fmtAmount } from "@/components/nutrient-meter";
import { LimitsSummary } from "@/components/profile-form";
import { Button, ButtonLink, Card, Spinner } from "@/components/ui";
import { dayLabel, dayStatus } from "@/lib/client/plan-utils";
import { FODMAP_LABELS, NUTRIENT_META } from "@/lib/domain/types";
import { keyNutrients } from "@/lib/engine/explain";
import { getRecipeInfo } from "@/lib/engine/recipe-info";
import { limitsFor } from "@/lib/rules/resolve";
import { CKD_STAGE_LABELS } from "@/lib/rules/profiles";
import { useAppState } from "@/lib/store/app-state";

/** Printable summary for the user's doctor or dietitian ("Save as PDF" from the print dialog). */
export default function ReportPage() {
  const { state, ready } = useAppState();
  const { profile, plan } = state;
  if (!ready) return <Spinner />;
  if (!profile || !plan) {
    return (
      <Card className="mx-auto max-w-lg p-8 text-center">
        <h1 className="text-xl font-semibold">Nothing to report yet</h1>
        <p className="mt-2 text-muted">Create a meal plan first.</p>
        <ButtonLink href="/plan" className="mt-6">Go to plan</ButtonLink>
      </Card>
    );
  }
  const rules = plan.rulesSnapshot;
  const nutrients = keyNutrients(rules);
  const avg = (n: (typeof nutrients)[number]) => plan.days.reduce((s, d) => s + d.totals[n], 0) / plan.days.length;
  const labs = profile.labs ?? {};

  return (
    <div className="mx-auto max-w-4xl text-sm">
      <div className="no-print mb-6 flex flex-wrap justify-between gap-3">
        <p className="text-muted">Print this page or choose “Save as PDF” to share it with your care team.</p>
        <Button onClick={() => window.print()}>Print / save as PDF</Button>
      </div>

      <header className="mb-6 border-b border-line pb-4">
        <h1 className="text-2xl font-semibold">Meal plan summary for review</h1>
        <p className="text-muted">
          Generated by MedPlate on {new Date(plan.createdAt).toLocaleDateString("en-US", { dateStyle: "long" })}. Values are estimates
          from USDA nutrient data.
        </p>
      </header>

      <section className="print-break mb-6">
        <h2 className="mb-2 text-lg font-semibold">Patient-entered profile</h2>
        <dl className="grid grid-cols-2 gap-x-6 gap-y-1 sm:grid-cols-3">
          <div><dt className="text-muted">Diets</dt><dd>{profile.diets.join(", ") || "none"}</dd></div>
          {profile.ckdStage && <div><dt className="text-muted">CKD</dt><dd>{CKD_STAGE_LABELS[profile.ckdStage]}</dd></div>}
          {profile.fodmapPhase && <div><dt className="text-muted">FODMAP phase</dt><dd className="capitalize">{profile.fodmapPhase}</dd></div>}
          {profile.fodmapTriggers?.length ? <div><dt className="text-muted">FODMAP triggers</dt><dd>{profile.fodmapTriggers.map((g) => FODMAP_LABELS[g]).join(", ")}</dd></div> : null}
          <div><dt className="text-muted">Age / sex</dt><dd>{profile.age} / {profile.sex}</dd></div>
          <div><dt className="text-muted">Height / weight</dt><dd>{profile.heightCm} cm / {profile.weightKg} kg</dd></div>
          {labs.egfr !== undefined && <div><dt className="text-muted">eGFR</dt><dd>{labs.egfr}</dd></div>}
          {labs.potassium !== undefined && <div><dt className="text-muted">Serum K</dt><dd>{labs.potassium} mmol/L</dd></div>}
          {labs.phosphorus !== undefined && <div><dt className="text-muted">Serum phosphorus</dt><dd>{labs.phosphorus} mg/dL</dd></div>}
          {labs.a1c !== undefined && <div><dt className="text-muted">HbA1c</dt><dd>{labs.a1c}%</dd></div>}
          {profile.allergies.length > 0 && <div><dt className="text-muted">Allergies</dt><dd>{profile.allergies.join(", ")}</dd></div>}
        </dl>
      </section>

      <section className="print-break mb-6">
        <h2 className="mb-2 text-lg font-semibold">Limits used for this plan</h2>
        <LimitsSummary rules={rules} />
      </section>

      <section className="print-break mb-6">
        <h2 className="mb-2 text-lg font-semibold">Daily totals</h2>
        <div className="overflow-x-auto">
          <table className="w-full border border-line tabular-nums">
            <thead className="bg-surface-2 text-left text-xs">
              <tr>
                <th className="px-2 py-1.5">Day</th>
                {nutrients.map((n) => <th key={n} className="px-2 py-1.5">{NUTRIENT_META[n].label}</th>)}
                <th className="px-2 py-1.5">Status</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-line">
              {plan.days.map((d) => (
                <tr key={d.day}>
                  <td className="px-2 py-1.5">{dayLabel(plan, d.day, "long")}</td>
                  {nutrients.map((n) => {
                    const max = n === "kcal" ? undefined : limitsFor(rules, "day", n).max?.value;
                    return (
                      <td key={n} className={`px-2 py-1.5 ${max !== undefined && d.totals[n] > max ? "font-semibold text-danger" : ""}`}>
                        {fmtAmount(d.totals[n], n)}
                      </td>
                    );
                  })}
                  <td className="px-2 py-1.5">{{ ok: "all limits met", warn: "target missed", danger: "limit exceeded" }[dayStatus(d)]}</td>
                </tr>
              ))}
              <tr className="bg-surface-2 font-medium">
                <td className="px-2 py-1.5">Average</td>
                {nutrients.map((n) => <td key={n} className="px-2 py-1.5">{fmtAmount(avg(n), n)}</td>)}
                <td />
              </tr>
            </tbody>
          </table>
        </div>
        {plan.warnings.length > 0 && (
          <ul className="mt-2 list-disc pl-5 text-warn">{plan.warnings.map((w) => <li key={w}>{w}</li>)}</ul>
        )}
      </section>

      <section className="print-break">
        <h2 className="mb-2 text-lg font-semibold">Meals</h2>
        <table className="w-full border border-line">
          <tbody className="divide-y divide-line">
            {plan.days.map((d) => (
              <tr key={d.day} className="align-top">
                <td className="w-32 px-2 py-1.5 font-medium">{dayLabel(plan, d.day, "long")}</td>
                <td className="px-2 py-1.5">
                  {d.meals.map((m) => (
                    <div key={m.slot}>
                      <span className="capitalize text-muted">{m.slot}:</span> {getRecipeInfo(m.recipeId).recipe.title}
                      {m.portion !== 1 && ` (${m.portion}×)`}
                    </div>
                  ))}
                </td>
              </tr>
            ))}
          </tbody>
        </table>
      </section>
    </div>
  );
}
